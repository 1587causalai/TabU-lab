def test_unknown_model_is_nonzero(capsys) -> None:
    assert main(["models", "show", "not-a-model", "--json"]) == 2
    assert "unknown model contract" in capsys.readouterr().err


def test_models_render_tex_writes_standalone_projection(tmp_path, capsys) -> None:
    output = tmp_path / "tabuf.generated.tex"

    assert main(["models", "render-tex", "tabuf", "--output", str(output)]) == 0

    assert output.is_file()
    assert "wrote:" in capsys.readouterr().out
    rendered = output.read_text(encoding="utf-8")
    assert rendered.startswith("% Generated by `tabu-lab models render-tex`")
    assert r"\section{Ordered mathematical construction}" in rendered
