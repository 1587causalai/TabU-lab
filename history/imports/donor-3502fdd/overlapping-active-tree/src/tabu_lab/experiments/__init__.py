def __getattr__(name: str):
    """Load the R1 adapter lazily to keep the adapters package acyclic."""

    if name in {"R1RunReceipt", "R1SeedMetrics", "run_r1", "validate_r1_binding"}:
        from . import r1_runner

        return getattr(r1_runner, name)
    raise AttributeError(f"module {__name__!r} has no attribute {name!r}")
